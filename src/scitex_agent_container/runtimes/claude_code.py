from ..config import AgentConfig
from .base import RuntimeBase
from .screen import ScreenManager

logger = logging.getLogger(__name__)


def _setup_claude_md(config: AgentConfig, workdir: str) -> None:
    """Generate and inject an agent-container section into CLAUDE.md.

    Uses HTML comment tags to delimit the managed section so it can be
    updated or removed without touching user content.
    """
    claude_dir = Path(workdir) / ".claude"
    claude_md = claude_dir / "CLAUDE.md"

    # Read existing content
    existing = ""
    if claude_md.exists():
        existing = claude_md.read_text()

    # Build the section content
    agent_id = config.name
    role = config.env.get("CLAUDE_AGENT_ROLE", config.labels.get("role", ""))
    agent_env_id = config.env.get("CLAUDE_AGENT_ID", config.name)

    lines = [
        f'<!-- agent-container:start id="{agent_id}" -->',
        f"## Agent: {agent_id} (auto-generated by scitex-agent-container)",
        "",
    ]

    if config.skills.required:
        lines.append("### Required Skills")
        lines.append("Load these skills at startup:")
        lines.append("```skills")
        for skill in config.skills.required:
            lines.append(skill)
        lines.append("```")
        lines.append("")

    if config.skills.available:
        lines.append("### Available Skills")
        lines.append("These skills can be used when needed:")
        lines.append("```skills")
        for skill in config.skills.available:
            lines.append(skill)
        lines.append("```")
        lines.append("")

    lines.append("### Agent Role")
    if role:
        lines.append(f"- Role: {role}")
    lines.append(f"- ID: {agent_env_id}")
    lines.append(f'<!-- agent-container:end id="{agent_id}" -->')

    section = "\n".join(lines)

    # Replace or append
    pattern = (
        rf'<!-- agent-container:start id="{re.escape(agent_id)}" -->.*?'
        rf'<!-- agent-container:end id="{re.escape(agent_id)}" -->'
    )
    if re.search(pattern, existing, re.DOTALL):
        updated = re.sub(pattern, section, existing, flags=re.DOTALL)
    else:
        separator = "\n\n" if existing and not existing.endswith("\n\n") else (
            "\n" if existing and not existing.endswith("\n") else ""
        )
        updated = existing + separator + section + "\n"

    claude_dir.mkdir(parents=True, exist_ok=True)
    claude_md.write_text(updated)
    logger.info("CLAUDE.md updated for agent %s at %s", agent_id, claude_md)


def _cleanup_claude_md(config: AgentConfig, workdir: str) -> None:
    """Remove the agent-container section from CLAUDE.md."""
    claude_md = Path(workdir) / ".claude" / "CLAUDE.md"
    if not claude_md.exists():
        return

    existing = claude_md.read_text()
    agent_id = config.name

    pattern = (
        rf'\n*<!-- agent-container:start id="{re.escape(agent_id)}" -->.*?'
        rf'<!-- agent-container:end id="{re.escape(agent_id)}" -->\n?'
    )
    updated = re.sub(pattern, "", existing, flags=re.DOTALL)

    if updated != existing:
        claude_md.write_text(updated)
        logger.info("CLAUDE.md cleaned up for agent %s at %s", agent_id, claude_md)


class _SSHRemote:
    """Helper for executing commands on a remote machine via SSH."""

    SSH_OPTS = [
        "-o", "BatchMode=yes",
        "-o", "StrictHostKeyChecking=accept-new",
        "-o", "ConnectTimeout=10",
    ]

    @staticmethod
    def _ssh_base(config: AgentConfig) -> list[str]:
        """Build the base SSH command with options."""
        cmd = ["ssh"] + _SSHRemote.SSH_OPTS
        if config.remote.key:
            cmd += ["-i", config.remote.key]
        if config.remote.port != 22:
            cmd += ["-p", str(config.remote.port)]
        cmd.append(f"{config.remote.user}@{config.remote.host}")
        return cmd

    @staticmethod
    def _scp_base(config: AgentConfig) -> list[str]:
        """Build the base SCP command with options."""
        cmd = ["scp"] + _SSHRemote.SSH_OPTS
        if config.remote.key:
            cmd += ["-i", config.remote.key]
        if config.remote.port != 22:
            cmd += ["-P", str(config.remote.port)]
        return cmd

    @staticmethod
    def copy_config(config: AgentConfig) -> str:
        """SCP the YAML config to the remote machine. Returns remote path."""
        remote_path = f"/tmp/{config.name}.yaml"
        local_path = config.config_path
        if not local_path:
            raise RuntimeError(
                f"Cannot deploy '{config.name}' remotely: config_path is not set"
            )

        scp_cmd = _SSHRemote._scp_base(config)
        target = f"{config.remote.user}@{config.remote.host}:{remote_path}"
        scp_cmd += [local_path, target]

        logger.info("SCP config to remote: %s -> %s", local_path, target)
        result = subprocess.run(scp_cmd, capture_output=True, text=True, timeout=30)
        if result.returncode != 0:
            raise RuntimeError(
                f"Failed to copy config to {config.remote.host}: {result.stderr.strip()}"
            )
        return remote_path

    @staticmethod
    def run(config: AgentConfig, remote_cmd: str, timeout: int = 30) -> subprocess.CompletedProcess:
        """Execute a command on the remote host via SSH."""
        ssh_cmd = _SSHRemote._ssh_base(config)
        ssh_cmd.append(remote_cmd)

        logger.info("SSH [%s]: %s", config.remote.host, remote_cmd)
        result = subprocess.run(ssh_cmd, capture_output=True, text=True, timeout=timeout)
        if result.returncode != 0:
            logger.warning(
                "SSH command failed on %s (exit %d): %s",
                config.remote.host, result.returncode, result.stderr.strip(),
            )
        return result

    @staticmethod
    def start(config: AgentConfig) -> bool:
        """Deploy and start agent on remote machine."""
        remote_path = _SSHRemote.copy_config(config)
        result = _SSHRemote.run(
            config,
            f"scitex-agent-container start {remote_path}",
            timeout=60,
        )
        if result.returncode != 0:
            raise RuntimeError(
                f"Failed to start agent '{config.name}' on {config.remote.host}: "
                f"{result.stderr.strip()}"
            )
        logger.info(
            "Agent '%s' started on remote host %s", config.name, config.remote.host
        )
        return True

    @staticmethod
    def stop(config: AgentConfig) -> bool:
        """Stop agent on remote machine."""
        result = _SSHRemote.run(
            config,
            f"scitex-agent-container stop {config.name}",
            timeout=30,
        )
        if result.returncode != 0:
            logger.error(
                "Failed to stop agent '%s' on %s: %s",
                config.name, config.remote.host, result.stderr.strip(),
            )
            return False
        logger.info(
            "Agent '%s' stopped on remote host %s", config.name, config.remote.host
        )
        return True

    @staticmethod
    def is_running(config: AgentConfig) -> bool:
        """Check if agent is running on remote machine."""
        result = _SSHRemote.run(
            config,
            f"scitex-agent-container status {config.name} --json",
            timeout=15,
        )
        if result.returncode != 0:
            return False
        try:
            data = json.loads(result.stdout)
            return data.get("status") == "running"
        except (json.JSONDecodeError, KeyError):
            return False

    @staticmethod
    def logs(config: AgentConfig, lines: int = 50) -> str:
        """Get logs from remote agent."""
        result = _SSHRemote.run(
            config,
            f"scitex-agent-container logs {config.name} -n {lines}",
            timeout=15,
        )
        if result.returncode != 0:
            return f"[SSH error] {result.stderr.strip()}"
        return result.stdout


class ClaudeCodeRuntime(RuntimeBase):
    """Runtime for launching Claude Code agents in screen sessions."""

    def _build_command(self, config: AgentConfig) -> str:
        """Build the claude CLI command from config."""
        parts = ["claude"]
        parts.append(f"--model '{config.model}'")

        for channel in config.claude.channels:
            parts.append(f"--channels {channel}")

        for flag in config.claude.flags:
            parts.append(flag)

        if config.claude.session == "continue":
            parts.append("--continue")

        return " ".join(parts)

    def _build_env_exports(self, config: AgentConfig) -> str:
        """Build export statements from env dict."""
        lines = []
        for key, value in config.env.items():
            lines.append(f'export {key}="{value}"')
        return "\n".join(lines)

    def _watchdog_screen_name(self, config: AgentConfig) -> str:
        """Derive a screen session name for the watchdog."""
        return f"{config.screen_name}-watchdog"

    def _start_watchdog(self, config: AgentConfig) -> bool:
        """Start telegrammer-watchdog in a companion screen session."""
        if not config.watchdog.enabled:
            return True

        watchdog_bin = shutil.which("telegrammer-watchdog")
        if watchdog_bin is None:
            # Try importing the package to resolve the script path
            try:
                from claude_code_telegrammer import get_bin_path

                watchdog_bin = get_bin_path("telegrammer-watchdog")
            except (ImportError, FileNotFoundError):
                logger.warning(
                    "Watchdog enabled but telegrammer-watchdog not found. "
                    "Install claude-code-telegrammer: "
                    "pip install claude-code-telegrammer"
                )
                return False

        wd = config.watchdog
        env_exports = (
            f'export TELEGRAMMER_SESSION="{config.screen_name}"\n'
            f'export TELEGRAMMER_WATCHDOG_INTERVAL="{wd.interval}"\n'
            f'export TELEGRAMMER_RESP_Y_N="{wd.resp_y_n}"\n'
            f'export TELEGRAMMER_RESP_Y_Y_N="{wd.resp_y_y_n}"\n'
            f'export TELEGRAMMER_RESP_WAITING="{wd.resp_waiting}"'
        )

        watchdog_session = self._watchdog_screen_name(config)
        cmd = f"{watchdog_bin} --session {config.screen_name} --interval {wd.interval}"

        started = ScreenManager.start(
            session_name=watchdog_session,
            command=cmd,
            workdir=config.expanded_workdir,
            env_exports=env_exports,
        )

        if started:
            logger.info("Watchdog started in screen session: %s", watchdog_session)
        else:
            logger.error("Failed to start watchdog screen session: %s", watchdog_session)

        return started

    def _stop_watchdog(self, config: AgentConfig) -> bool:
        """Stop the companion watchdog screen session."""
        if not config.watchdog.enabled:
            return True

        watchdog_session = self._watchdog_screen_name(config)
        if ScreenManager.exists(watchdog_session):
            stopped = ScreenManager.stop(watchdog_session)
            if stopped:
                logger.info("Watchdog stopped: %s", watchdog_session)
            return stopped
        return True

    def _setup_telegram_access(self, config: AgentConfig) -> None:
        """Write access.json for Telegram channel if configured."""
        tg = config.telegram
        if not (tg.auto_connect and tg.allowed_users):
            return

        access_dir = Path.home() / ".claude" / "channels" / "telegram"
        access_dir.mkdir(parents=True, exist_ok=True)
        access_file = access_dir / "access.json"

        access_data = {
            "dmPolicy": "pairing",
            "allowFrom": tg.allowed_users,
        }

        access_file.write_text(json.dumps(access_data, indent=2) + "\n")
        logger.info(
            "Telegram access.json written with %d allowed users: %s",
            len(tg.allowed_users),
            access_file,
        )

    def _run_startup_commands(self, config: AgentConfig) -> None:
        """Send startup commands to the screen session with delays.

        Runs in a background thread so start() returns immediately.
        """
        for sc in config.startup_commands:
            if sc.delay > 0:
                time.sleep(sc.delay)
            try:
                subprocess.run(
                    ["screen", "-S", config.screen_name, "-X", "stuff", f"{sc.command}\r"],
                    check=False,
                    capture_output=True,
                )
                logger.info(
                    "Sent startup command to %s (delay=%ds): %s",
                    config.screen_name,
                    sc.delay,
                    sc.command,
                )
            except Exception:
                logger.exception(
                    "Failed to send startup command to %s: %s",
                    config.screen_name,
                    sc.command,
                )

    def _post_start_tasks(self, config: AgentConfig) -> None:
        """Run post-start tasks: telegram setup and startup commands."""
        self._setup_telegram_access(config)
        self._run_startup_commands(config)

    def start(self, config: AgentConfig) -> bool:
        """Start a Claude Code agent."""
        # If remote, delegate to SSH
        if config.remote.is_remote:
            return _SSHRemote.start(config)

        # If container runtime is requested, delegate
        if config.container.runtime != "none":
            from .docker import DockerRuntime
            from .apptainer import ApptainerRuntime

            if config.container.runtime == "docker":
                return DockerRuntime().start(config)
            elif config.container.runtime == "apptainer":
                return ApptainerRuntime().start(config)

        cmd = self._build_command(config)
        env_exports = self._build_env_exports(config)
        workdir = config.expanded_workdir

        # Inject agent section into CLAUDE.md before launching
        _setup_claude_md(config, workdir)

        started = ScreenManager.start(
            session_name=config.screen_name,
            command=cmd,
            workdir=workdir,
            env_exports=env_exports,
        )

        # Start watchdog after the agent is running
        if started:
            self._start_watchdog(config)

            # Run post-start tasks in background thread
            has_tasks = (
                (config.telegram.auto_connect and config.telegram.allowed_users)
                or config.startup_commands
            )
            if has_tasks:
                thread = threading.Thread(
                    target=self._post_start_tasks,
                    args=(config,),
                    daemon=True,
                    name=f"post-start-{config.screen_name}",
                )
                thread.start()

        return started

    def stop(self, config: AgentConfig) -> bool:
        """Stop a Claude Code agent."""
        # If remote, delegate to SSH
        if config.remote.is_remote:
            return _SSHRemote.stop(config)

        # Stop watchdog first
        self._stop_watchdog(config)

        if config.container.runtime != "none":
            from .docker import DockerRuntime
            from .apptainer import ApptainerRuntime

            if config.container.runtime == "docker":
                return DockerRuntime().stop(config)
            elif config.container.runtime == "apptainer":
                return ApptainerRuntime().stop(config)

        # Clean up agent section from CLAUDE.md
        _cleanup_claude_md(config, config.expanded_workdir)

        return ScreenManager.stop(config.screen_name)

    def is_running(self, config: AgentConfig) -> bool:
        """Check if the Claude Code agent is running."""
        if config.remote.is_remote:
            return _SSHRemote.is_running(config)

        if config.container.runtime == "docker":
            from .docker import DockerRuntime
            return DockerRuntime().is_running(config)
        elif config.container.runtime == "apptainer":
            from .apptainer import ApptainerRuntime
            return ApptainerRuntime().is_running(config)

        return ScreenManager.exists(config.screen_name)

    def logs(self, config: AgentConfig, lines: int = 50) -> str:
        """Get logs from the Claude Code agent."""
        if config.remote.is_remote:
            return _SSHRemote.logs(config, lines)

        if config.container.runtime == "docker":
            from .docker import DockerRuntime
            return DockerRuntime().logs(config, lines)
        elif config.container.runtime == "apptainer":
            from .apptainer import ApptainerRuntime
            return ApptainerRuntime().logs(config, lines)

        return ScreenManager.capture_logs(config.screen_name, lines)
