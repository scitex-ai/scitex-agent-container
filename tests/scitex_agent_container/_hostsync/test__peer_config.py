def test_is_generated_true_for_rendered_output(master_cfg):
    # Arrange
    text = render_peer_config("spartan", master_cfg, now=_NOW, master_sha=_SHA)
    # Act
    verdict = is_generated(text)
    # Assert
    assert verdict


def test_is_generated_false_for_hand_written_text():
    # Arrange
    hand = "host:\n  aliases: {}\npeers:\n  mba: {ssh: m}\n"
    # Act
    verdict = is_generated(hand)
    # Assert
    assert not verdict


def test_is_generated_false_for_empty_text():
    # Arrange
    empty = ""
    # Act
    verdict = is_generated(empty)
    # Assert
    assert not verdict


def test_golden_first_line_starts_with_the_header_mark():
    # Arrange — the mark is the contract every consumer (verdicts, CRUD
    # guard) keys on.
    first_line = _GOLDEN.split("\n", 1)[0]
    # Act
    starts = first_line.startswith(GENERATED_HEADER_MARK)
    # Assert
    assert starts


def test_strip_generated_stamp_removes_only_the_stamp_line():
    # Arrange
    # (the golden config carries exactly one '# generated:' line)
    # Act
    stripped = strip_generated_stamp(_GOLDEN)
    # Assert — the volatile line is gone.
    assert "# generated:" not in stripped


def test_strip_generated_stamp_keeps_every_other_line():
    # Arrange
    expected = _GOLDEN.replace(
        "# generated: 2026-07-16T08:00:00+00:00 "
        "from master-config sha256:aabbccddeeff\n",
        "",
    )
    # Act
    stripped = strip_generated_stamp(_GOLDEN)
    # Assert — nothing else went with it.
    assert stripped == expected


def test_embedded_master_sha_reads_the_stamped_sha12():
    # Arrange
    # (the golden config stamps sha256:aabbccddeeff)
    # Act
    sha12 = embedded_master_sha(_GOLDEN)
    # Assert
    assert sha12 == "aabbccddeeff"


def test_embedded_master_sha_empty_for_hand_text():
    # Arrange
    hand = "peers: {}\n"
    # Act
    sha12 = embedded_master_sha(hand)
    # Assert
    assert sha12 == ""
