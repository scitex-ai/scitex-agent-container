def test_render_raises_on_a_name_yaml_cannot_take_plain(master_cfg):
    # Arrange — a peer name that would need quoting must FAIL LOUDLY at
    # render time, never ship as a corrupted client config.
    bad_peer_name = "bad: name"
    # Act
    # Assert — the raise IS the assertion.
    with pytest.raises(ValueError):
        render_peer_config(bad_peer_name, master_cfg, now=_NOW, master_sha=_SHA)


def test_render_stamp_defaults_to_unknown_without_master_sha(master_cfg):
    # Arrange
    # (empty master_sha must still render honestly)
    # Act
    text = render_peer_config("spartan", master_cfg, now=_NOW)
    # Assert
    assert "sha256:unknown" in text


